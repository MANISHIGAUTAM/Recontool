"""Render the inventory dict into JSON + Markdown + per-tool capability docs."""
from __future__ import annotations

import json
import re
from pathlib import Path

# section number -> pipeline stage + typical required input (heuristic, documented as such)
SECTION_STAGE = {
    1: ("Seed discovery (internet-wide search)", "domain / org / ip / asn"),
    2: ("Subdomain discovery & DNS resolution", "domain / subdomain"),
    3: ("Network intelligence (WHOIS/ASN/BGP)", "domain / ip / asn"),
    4: ("URL/dork/index harvesting", "domain / live_host / url"),
    5: ("Web tech fingerprinting & probing", "live_host / url"),
    6: ("Historical & archive harvesting", "domain / live_host"),
    7: ("Email / username / identity recon", "domain / email / person / username"),
    8: ("Social media recon", "username / handle / org"),
    9: ("Source-code & secret recon", "org / domain / keyword"),
    10: ("Cloud & storage recon", "org / domain / keyword"),
    11: ("Metadata & document recon", "file / document / url"),
    12: ("Malware / IOC / vuln intel", "ip / domain / url / hash / cpe"),
    13: ("Visual recon & screenshotting", "live_host / url"),
    14: ("Frameworks & automation (orchestration)", "domain (scope)"),
    15: ("Physical / geo / wireless recon", "bssid / coords / org"),
    16: ("Dark web & onion recon", "keyword / onion address"),
    17: ("APIs & intelligence feeds (enrichment)", "domain / ip / email"),
    18: ("Reference index (tool discovery, not executed)", "n/a"),
    19: ("Common recon workflow preset", "domain (scope)"),
}


def _sec_num(section: str) -> int:
    m = re.match(r"\s*(\d+)\.", section or "")
    return int(m.group(1)) if m else 0


def write_all(inv: dict, data_dir: Path, inv_doc_dir: Path, tools_doc_dir: Path, repo: Path):
    data_dir.mkdir(parents=True, exist_ok=True)
    inv_doc_dir.mkdir(parents=True, exist_ok=True)
    tools_doc_dir.mkdir(parents=True, exist_ok=True)

    tools = inv["tools"]
    raw_rows = inv["raw_rows"]
    stats = inv["stats"]

    # ── 1. machine-readable JSON ──────────────────────────────────────────────
    inventory_json = {k: inv[k] for k in ("generated_at", "source", "note", "stats")}
    inventory_json["tools"] = tools
    (data_dir / "tool_inventory.json").write_text(json.dumps(inventory_json, indent=2))

    rows_clean = [{k: r[k] for k in r if not k.startswith("_")} for r in raw_rows]
    (data_dir / "tool_rows_raw.json").write_text(
        json.dumps({"generated_at": inv["generated_at"], "source": inv["source"],
                    "row_count": len(rows_clean), "rows": rows_clean}, indent=2)
    )

    # ── 2. human-readable Markdown inventory ──────────────────────────────────
    (inv_doc_dir / "TOOL-INVENTORY.md").write_text(_render_inventory_md(inv))

    # ── 3. per-tool capability docs ───────────────────────────────────────────
    for t in tools:
        (tools_doc_dir / f"{t['slug']}.md").write_text(_render_tool_md(t, raw_rows))
    (tools_doc_dir / "README.md").write_text(_render_tools_index(tools))

    print("inventory build complete")
    print(f"  raw rows           : {stats['raw_rows']}")
    print(f"  canonical tools    : {stats['canonical_tools']}")
    print(f"  rows collapsed     : {stats['duplicate_rows_collapsed']}")
    print(f"  multi-section tools: {stats['multi_section_tools']}")
    print(f"  web-only tools     : {stats['web_only_count']}")
    print("  outputs            : data/tool_inventory.json, data/tool_rows_raw.json,")
    print(f"                       docs/inventory/TOOL-INVENTORY.md, docs/tools/*.md "
          f"({len(tools)} files)")


def _render_inventory_md(inv: dict) -> str:
    tools = inv["tools"]
    stats = inv["stats"]
    L = []
    L.append("# Recon Tool Inventory (exhaustive, normalized)\n")
    L.append(f"> Generated by `recontool.inventory.build_inventory` from "
             f"`{inv['source']}`.\n>\n> {inv['note']}\n")
    L.append("## Summary\n")
    L.append(f"- **Raw spreadsheet rows:** {stats['raw_rows']} (every row preserved)")
    L.append(f"- **Canonical tools (deduplicated):** {stats['canonical_tools']}")
    L.append(f"- **Duplicate rows collapsed:** {stats['duplicate_rows_collapsed']}")
    L.append(f"- **Tools spanning multiple sections:** {stats['multi_section_tools']}")
    L.append(f"- **Web/GUI-only tools:** {stats['web_only_count']}")
    L.append("- **By classification:** "
             + ", ".join(f"{k}={v}" for k, v in stats["by_classification"].items()))
    L.append("- **By cost tier:** "
             + ", ".join(f"{k}={v}" for k, v in stats["by_cost_tier"].items()))
    L.append("")
    L.append("**Provenance:** every tool below is `extracted_from_spreadsheet`. "
             "Genuinely missing categories/tools we recommend adding are kept "
             "separate in [`../pipeline/01-gap-analysis.md`](../pipeline/01-gap-analysis.md) "
             "and are never merged into this extracted inventory.\n")

    # index by section
    L.append("## Sections (as in the spreadsheet)\n")
    for s in stats["sections"]:
        n = _sec_num(s)
        members = [t for t in tools if any(_sec_num(x) == n for x in t["sections"])]
        L.append(f"- **{s}** — {len(members)} tools")
    L.append("")

    # master table
    L.append("## Canonical tool table\n")
    L.append("| Tool | Class | Integration | Cost | Scale | Reliability | "
             "Appears | Sections | Caveats |")
    L.append("|------|-------|-------------|------|-------|-------------|---------|"
             "----------|---------|")
    for t in tools:
        modes = ",".join(t["integration_modes"]) or ("web" if t["web_only"] else "?")
        secs = ",".join(str(_sec_num(s)) for s in t["sections"])
        cav = str(len(t["caveats"])) if t["caveats"] else "-"
        doc = f"[{_esc(t['name'])}](../tools/{t['slug']}.md)"
        L.append(f"| {doc} | {t['classification']} | {modes} | {t['cost_tier']} | "
                 f"{_esc(t['scale'])} | {_esc(t['reliability'])} | {t['appearances']} | "
                 f"{secs} | {cav} |")
    L.append("")

    # multi-section / duplicates section
    multi = [t for t in tools if len(t["sections"]) > 1 or t["appearances"] > 1]
    L.append("## Tools appearing multiple times / across categories\n")
    L.append("These are deduplicated to one canonical record; all memberships kept.\n")
    L.append("| Tool | Appearances | Sections | Categories |")
    L.append("|------|-------------|----------|------------|")
    for t in sorted(multi, key=lambda x: -x["appearances"]):
        secs = ", ".join(str(_sec_num(s)) for s in t["sections"])
        cats = ", ".join(_esc(c) for c in t["categories"])
        L.append(f"| {_esc(t['name'])} | {t['appearances']} | {secs} | {cats} |")
    L.append("")

    # possible aliases (informational, not merged)
    aliased = [t for t in tools if t["possible_aliases"]]
    L.append("## Possible aliases / same-ecosystem variants (NOT merged)\n")
    L.append("Reported for human review only — kept as separate canonical records "
             "because the spreadsheet lists them under distinct names.\n")
    L.append("| Tool | Possibly related to |")
    L.append("|------|---------------------|")
    seen_groups = set()
    for t in sorted(aliased, key=lambda x: x["name"].lower()):
        grp = tuple(sorted([t["name"]] + t["possible_aliases"]))
        if grp in seen_groups:
            continue
        seen_groups.add(grp)
        L.append(f"| {_esc(t['name'])} | {_esc(', '.join(t['possible_aliases']))} |")
    L.append("")
    L.append("Full machine-readable data: [`../../data/tool_inventory.json`]"
             "(../../data/tool_inventory.json) and "
             "[`../../data/tool_rows_raw.json`](../../data/tool_rows_raw.json).\n")
    return "\n".join(L)


def _render_tool_md(t: dict, raw_rows: list[dict]) -> str:
    sec_nums = sorted({_sec_num(s) for s in t["sections"]})
    stages = [SECTION_STAGE.get(n, ("(uncategorized)", "domain")) for n in sec_nums]
    pipeline_pos = "; ".join(sorted({s[0] for s in stages})) or "(uncategorized)"
    req_input = " | ".join(sorted({s[1] for s in stages})) or "domain"
    modes = t["integration_modes"]
    rows = [r for r in raw_rows if r["row_id"] in t["row_refs"]]

    L = []
    L.append(f"# {t['name']}\n")
    L.append(f"> Provenance: {t['provenance']} · canonical slug `{t['slug']}` · "
             f"{t['appearances']} source row(s).\n")
    purpose = t["best_use"][0] if t["best_use"] else (t["categories"][0] if t["categories"] else "Recon")
    L.append(f"**Purpose.** {_esc(purpose)}."
             + (f" {_esc(t['notes'][0])}." if t["notes"] else ""))
    L.append("")
    L.append("| Field | Value |")
    L.append("|-------|-------|")
    L.append(f"| Category(s) | {_esc(', '.join(t['categories']))} |")
    L.append(f"| Classification | **{t['classification']}** "
             f"(source: {', '.join(t['passive_active_values']) or 'n/a'}) |")
    L.append(f"| Integration | {', '.join(modes) or ('web/gui only' if t['web_only'] else 'unspecified')} |")
    L.append(f"| Cost | {t['cost_tier']} ({', '.join(t['free_paid_values']) or 'n/a'}) |")
    L.append(f"| Scale | {_esc(t['scale']) or 'n/a'} |")
    L.append(f"| Reliability / worth | {_esc(t['reliability'])} (score {t['confidence_score']}) |")
    L.append(f"| Data quality (source) | {_esc(', '.join(t['data_quality_values']) or 'n/a')} |")
    L.append(f"| Pipeline position | {_esc(pipeline_pos)} |")
    L.append(f"| Required input | `{_esc(req_input)}` |")
    L.append("")

    # invocation
    L.append("## Invocation\n")
    if t["web_only"]:
        L.append("Web/GUI/manual source — **no documented CLI/API** in the spreadsheet. "
                 "Use via browser or a scripted headless browser; not part of the "
                 "automated CLI chain by default.\n")
    elif "cli" in modes:
        L.append("```bash")
        L.append(f"{t['slug']} <target>   # exact flags: define in config/tools.yaml")
        L.append("```")
        if "api" in modes:
            L.append("> Also exposes an API. ", )
        L.append("> CLI flags are a placeholder — confirm against the installed tool "
                 "version pinned in `docker/install_tools.sh`.\n")
    elif "api" in modes:
        L.append("```text")
        L.append(f"# API integration (fill endpoint/auth in config/tools.yaml -> {t['slug']})")
        L.append("GET https://<provider-endpoint>/...   # key: see config/recontool.yaml")
        L.append("```")
        L.append("> Invocation template is a placeholder — wire the exact endpoint/flags "
                 "in `config/tools.yaml` and implement an adapter under "
                 "`recontool/adapters/`.\n")
    else:
        L.append("Integration mode not specified in source — classify before wiring.\n")

    L.append("## Inputs / outputs\n")
    L.append(f"- **Consumes:** `{_esc(req_input)}` (per pipeline position).")
    L.append("- **Produces:** normalized records (subdomains / ips / urls / services / "
             "findings as applicable) → mapped to the common schema in "
             "[`docs/D3-data-schema.md`](../D3-data-schema.md).")
    L.append("- **Output format (raw):** JSON/JSONL/text per tool; raw stored under "
             "`artifacts/<scan_id>/raw/`.\n")

    L.append("## Operational behavior\n")
    L.append(f"- **Confidence / false-positive risk:** worth=`{_esc(t['reliability'])}` "
             f"(score {t['confidence_score']}). "
             + ("Lower-tier source — corroborate with another tool before trusting."
                if t["confidence_score"] < 0.6 else
                "Higher-tier source — still corroborated via multi-source confidence scoring."))
    if "api" in modes:
        L.append("- **If it rate-limits / errors:** exponential backoff + retry; rotate "
                 "API key from pool; on repeated 401/403 disable for the run and audit.")
        L.append("- **If it returns nothing:** record an empty result with provenance "
                 "(not a failure); continue the pipeline.")
    elif "cli" in modes:
        L.append("- **If the binary is missing:** adapter reports unavailable (graceful "
                 "skip); install via `docker/install_tools.sh`.")
        L.append("- **If it returns nothing:** treat as empty (valid); do not block chain.")
    else:
        L.append("- **If unavailable / empty:** skip gracefully; never block the pipeline.")
    L.append("- **Scope safety:** active tools re-check scope before egress; out-of-scope "
             "targets are stored but never probed (see `docs/D6-opsec.md`).\n")

    if t["caveats"]:
        L.append("## Caveats\n")
        for c in t["caveats"]:
            L.append(f"- {_esc(c)}")
        L.append("")
    if t["possible_aliases"]:
        L.append("## Possibly related (not merged)\n")
        L.append(", ".join(_esc(a) for a in t["possible_aliases"]) + "\n")

    L.append("## Source rows (provenance)\n")
    L.append("| Section | Category | P/A | Free/Paid | CLI/API | Best use | Worth | Notes |")
    L.append("|---------|----------|-----|-----------|---------|----------|-------|-------|")
    for r in rows:
        L.append(f"| {_sec_num(r['section'])} | {_esc(r['category'])} | "
                 f"{_esc(r['passive_active'])} | {_esc(r['free_paid'])} | "
                 f"{_esc(r['cli_api'])} | {_esc(r['best_use'])} | {_esc(r['worth'])} | "
                 f"{_esc(r['notes'])} |")
    L.append("")
    return "\n".join(L)


def _render_tools_index(tools: list[dict]) -> str:
    L = ["# Per-Tool Capability Docs\n",
         f"Auto-generated from the inventory ({len(tools)} canonical tools). "
         "Each file documents purpose, classification, invocation, I/O, failure "
         "modes, confidence, and pipeline position.\n",
         "| Tool | Class | Integration | Doc |",
         "|------|-------|-------------|-----|"]
    for t in tools:
        modes = ",".join(t["integration_modes"]) or ("web" if t["web_only"] else "?")
        L.append(f"| {_esc(t['name'])} | {t['classification']} | {modes} | "
                 f"[{t['slug']}.md]({t['slug']}.md) |")
    L.append("")
    return "\n".join(L)


def _esc(s: str) -> str:
    return (s or "").replace("|", "\\|").replace("\n", " ").strip()
